/// Every Storage SOP class the SCP accepts by default.
pub fn all() -> impl Iterator<Item = &'static str> {
    STANDARD.iter().chain(RETIRED).copied()
}

#[cfg(test)]
mod tests {
    use super::*;
    use dicom_core::dictionary::UidDictionary as _;
    use dicom_dictionary_std::StandardSopClassDictionary;

    #[test]
    fn are_storage_sop_classes() {
        let mut seen = std::collections::HashSet::new();
        for uid in all() {
            assert!(seen.insert(uid), "{uid} listed twice");
            if let Some(entry) = StandardSopClassDictionary.by_uid(uid) {
                assert!(entry.name.contains("Storage"), "{uid}: {}", entry.name);
            }
        }
        assert!(STANDARD.contains(&CT_IMAGE_STORAGE));
    }
}
