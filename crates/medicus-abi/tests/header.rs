//! Keeps `include/medicus_addon.h` (the public C contract) in sync with `src/ffi.rs`.
//!
//! Regenerate after an intended ABI change with:
//! `UPDATE_HEADER=1 cargo test -p medicus-abi --test header`
#![allow(clippy::unwrap_used, clippy::expect_used)]

use std::path::Path;

const TYPES: &[&str] = &[
    "MdStr",
    "MdBuffer",
    "MdCompletion",
    "MdCancel",
    "MdReadStreamVtable",
    "MdReadStream",
    "MdStreamCompletion",
    "MdHostApi",
    "MdRange",
    "MdBlobStoreVtable",
    "MdEventHookVtable",
    "MdIndexStoreVtable",
    "MdServiceVtable",
    "MdRemoteNodeVtable",
    "MdHttpRoutesVtable",
    "MdAbiVersionFn",
    "MdManifestFn",
    "MdInitFn",
    "MdStatus",
];

fn generate() -> String {
    let crate_dir = env!("CARGO_MANIFEST_DIR");
    let mut config = cbindgen::Config {
        language: cbindgen::Language::C,
        // The include guard is written by hand so that the entry-point prototypes in the trailer
        // end up inside it.
        header: Some(
            "/* medicus addon ABI (see docs/adr/0001-addon-abi.md and the rules in\n \
             * crates/medicus-abi/src/ffi.rs). Generated by cbindgen; do not edit.\n \
             * Regenerate: UPDATE_HEADER=1 cargo test -p medicus-abi --test header */\n\n\
             #ifndef MEDICUS_ADDON_H\n\
             #define MEDICUS_ADDON_H"
                .into(),
        ),
        trailer: Some(
            "/* Marks the entry points as exported from the shared library. */\n\
             #if defined(_WIN32)\n\
             #define MEDICUS_ADDON_EXPORT __declspec(dllexport)\n\
             #else\n\
             #define MEDICUS_ADDON_EXPORT __attribute__((visibility(\"default\")))\n\
             #endif\n\n\
             #ifdef __cplusplus\nextern \"C\" {\n#endif\n\n\
             /* Entry points every addon exports. */\n\
             MEDICUS_ADDON_EXPORT uint32_t medicus_addon_abi_version(void);\n\
             MEDICUS_ADDON_EXPORT MdStr medicus_addon_manifest(void);\n\
             MEDICUS_ADDON_EXPORT MdStatus medicus_addon_init(const MdHostApi *host);\n\n\
             #ifdef __cplusplus\n}  /* extern \"C\" */\n#endif\n\n\
             #endif  /* MEDICUS_ADDON_H */"
                .into(),
        ),
        cpp_compat: true,
        usize_is_size_t: true,
        documentation: true,
        ..cbindgen::Config::default()
    };
    config.export.include = TYPES.iter().map(|s| (*s).to_owned()).collect();
    config.parse.parse_deps = false;
    let bindings = cbindgen::Builder::new()
        .with_config(config)
        .with_src(Path::new(crate_dir).join("src/ffi.rs"))
        .generate()
        .expect("cbindgen failed");
    let mut out = Vec::new();
    bindings.write(&mut out);
    String::from_utf8(out).unwrap()
}

#[test]
fn header_is_up_to_date() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../include/medicus_addon.h");
    let generated = generate();
    if std::env::var_os("UPDATE_HEADER").is_some() {
        std::fs::write(&path, &generated).unwrap();
        return;
    }
    let current = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        current == generated,
        "include/medicus_addon.h is out of date with src/ffi.rs.\n\
         If the ABI change is intended, bump MD_ABI_MINOR/MAJOR, note it in include/CHANGELOG.md \
         and run: UPDATE_HEADER=1 cargo test -p medicus-abi --test header"
    );
}
